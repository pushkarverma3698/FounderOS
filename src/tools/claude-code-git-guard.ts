/**
 * FounderOS — git guard for the claude_code executor.
 * ===================================================
 * The product repos take changes only through a reviewed PR. `/task` already works
 * that way (issue → Antigravity → draft PR → pr-brain gate). claude_code did not: one
 * Telegram approval gave a headless Claude a shell and a GitHub token with `repo`,
 * `admin:org` and `delete_repo`, and nothing stopped it pushing straight to an
 * integration or production branch. GitHub cannot stop it either — the Oplify repos
 * are private on the free plan, where branch protection is unavailable (checked
 * 2026-09-28: `gh api …/branches/main/protection` → 404 on both).
 *
 * So every claude_code run gets a pre-push hook through GIT_CONFIG_* environment
 * variables (command-line precedence, so it applies to every repo the run touches,
 * including ones it clones). For the repos on the dispatch allowlist the hook refuses
 * a push to main, master, beta or development. A feature branch and a draft PR still
 * work, and pr-brain gates that PR like any other. Every other repo — new projects,
 * demos, throwaway work — is untouched.
 *
 * This is an accident guard for an approved, well-meant run, not a sandbox: a shell
 * can unset the variables or use `--no-verify`. The brief says so up front, so the
 * model plans for a PR instead of discovering the refusal.
 */

import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DISPATCH_REPO_ALLOWLIST } from "./dispatch-repos.js";

/** Branches a claude_code run may never push to on a protected repo. */
export const PROTECTED_BRANCHES = ["main", "master", "beta", "development"] as const;

/**
 * The pre-push hook. The repo list is baked in rather than read from the
 * environment, so a run that loses the variable still has the rule.
 *
 * Four URLs are checked: the remote's url and pushurl as configured, $1 and $2. git hands the
 * hook $2 AFTER `url.<x>.insteadOf` rewriting, so $2 alone lets a rewrite rule hide
 * the real repository; for a push straight to a URL (no remote name) $1 is that
 * URL before rewriting.
 */
export function prePushHook(repos: readonly string[] = DISPATCH_REPO_ALLOWLIST): string {
  const repoList = repos.map((r) => r.toLowerCase()).join(" ");
  return `#!/bin/sh
# Generated by FounderOS src/tools/claude-code-git-guard.ts — do not edit here.
PROTECTED_REPOS="${repoList}"
PROTECTED_BRANCHES="${PROTECTED_BRANCHES.join(" ")}"

# https://user:token@github.com/Owner/Repo.git, git@github.com:Owner/Repo, ssh://… → owner/repo
norm() {
  printf '%s' "$1" | sed -E 's#^[a-z+]+://##; s#^[^@/]*@##; s#^github\\.com[:/]##; s#\\.git$##; s#/+$##' | tr 'A-Z' 'a-z'
}

repo=""
for u in "$(git config --get "remote.$1.url" 2>/dev/null)" "$(git config --get "remote.$1.pushurl" 2>/dev/null)" "$1" "$2"; do
  [ -n "$u" ] || continue
  n=$(norm "$u")
  for p in $PROTECTED_REPOS; do
    [ "$n" = "$p" ] && repo="$p"
  done
done
[ -n "$repo" ] || exit 0

status=0
while read -r local_ref local_sha remote_ref remote_sha; do
  branch="\${remote_ref#refs/heads/}"
  for p in $PROTECTED_BRANCHES; do
    if [ "$branch" = "$p" ]; then
      echo "claude_code: refused push to $branch on $repo. Product repos change only through a reviewed PR: push a feature branch and open a DRAFT PR to beta (pr-brain gates it), or file the work with /task." >&2
      status=1
    fi
  done
done
exit $status
`;
}

/** Where the hook is written: under the service user's home, never a shared /tmp. */
export function gitGuardDir(home: string = process.env["HOME"] ?? "/home/founderos"): string {
  return join(home, ".cache/founderos/claude-code-git-hooks");
}

/** Writes the hook (every run, so a code change reaches the next run). Returns the dir. */
export function installGitGuard(dir: string = gitGuardDir()): string {
  mkdirSync(dir, { recursive: true });
  const hook = join(dir, "pre-push");
  writeFileSync(hook, prePushHook());
  chmodSync(hook, 0o755);
  return dir;
}

/**
 * GIT_CONFIG_COUNT/KEY_n/VALUE_n that point core.hooksPath at the guard. Appends
 * after any entries the base environment already carries instead of replacing them.
 */
export function gitGuardEnv(hooksDir: string, base: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  const n = Number.parseInt(base["GIT_CONFIG_COUNT"] ?? "0", 10) || 0;
  return {
    GIT_CONFIG_COUNT: String(n + 1),
    [`GIT_CONFIG_KEY_${n}`]: "core.hooksPath",
    [`GIT_CONFIG_VALUE_${n}`]: hooksDir,
  };
}

/** Appended to every brief, so the plan is a PR from the start. */
export const REPO_POLICY_DIRECTIVE =
  "\n\n---\nRepo policy (always): " +
  DISPATCH_REPO_ALLOWLIST.join(", ") +
  " are product repos. Never push to their main, master, beta or development branch — a git hook " +
  "refuses it. Work on a feature branch and open a DRAFT pull request to beta with `gh pr create --draft`; " +
  "the review loop gates it. Other repos (new projects, demos) have no such limit.";
