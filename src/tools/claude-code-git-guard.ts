/**
 * FounderOS — git guard for the claude_code executor.
 * ===================================================
 * The product repos take changes only through a reviewed PR. `/task` already works
 * that way (issue → Antigravity → draft PR → pr-brain gate). claude_code did not: one
 * Telegram approval gave a headless Claude a shell and a GitHub token with `repo`,
 * `admin:org` and `delete_repo`, and nothing stopped it pushing straight to an
 * integration or production branch. GitHub cannot stop it either — the Oplify repos
 * are private on the free plan, where branch protection is unavailable (checked
 * 2026-09-28: `gh api …/branches/main/protection` → 404 on both).
 *
 * So every claude_code run gets a pre-push hook through GIT_CONFIG_* environment
 * variables (command-line precedence, so it applies to every repo the run touches,
 * including ones it clones). For the repos on the dispatch allowlist the hook refuses
 * a push to main, master, beta or development. A feature branch and a draft PR still
 * work, and pr-brain gates that PR like any other. Every other repo — new projects,
 * demos, throwaway work — is untouched.
 *
 * `gh` goes around git entirely (`gh pr merge`, `gh api …/contents -X PUT`), so the
 * run's PATH also starts with a `gh` wrapper that refuses merges, repo deletion and
 * edits, and API writes on the same repos, then execs the real gh for everything
 * else (found by the security review of PR #747).
 *
 * This is an accident guard for an approved, well-meant run, not a sandbox: a shell
 * can unset the variables, call the real gh by path, or use `--no-verify`. The brief
 * says so up front, so the model plans for a PR instead of discovering the refusal.
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { delimiter, join } from "node:path";
import { DISPATCH_REPO_ALLOWLIST } from "./dispatch-repos.js";

/** Branches a claude_code run may never push to on a protected repo. */
export const PROTECTED_BRANCHES = ["main", "master", "beta", "development"] as const;

/**
 * Shell function: any GitHub remote or repo reference → `owner/repo`, lowercased.
 * Lowercase first, then strip scheme, credentials, host (with www. and a port),
 * then trailing slashes, `.git`, trailing slashes again. Shapes that once slipped
 * through (security review of #747): `….git/`, `www.github.com`, `:443`, `HTTPS://`.
 */
const NORM_FN = `# any GitHub URL or owner/repo → owner/repo (lowercase)
norm() {
  printf '%s' "$1" | tr 'A-Z' 'a-z' | sed -E 's#^[a-z+]+://##; s#^[^@/]*@##; s#^(www\\.)?github\\.com(:[0-9]+)?[:/]##; s#/+$##; s#\\.git$##; s#/+$##'
}`;

function repoListOf(repos: readonly string[]): string {
  return repos.map((r) => r.toLowerCase()).join(" ");
}

/**
 * The pre-push hook. The repo list is baked in rather than read from the
 * environment, so a run that loses the variable still has the rule.
 *
 * Four URLs are checked: the remote's url and pushurl as configured, $1 and $2. git hands the
 * hook $2 AFTER `url.<x>.insteadOf` rewriting, so $2 alone lets a rewrite rule hide
 * the real repository; for a push straight to a URL (no remote name) $1 is that
 * URL before rewriting.
 */
export function prePushHook(repos: readonly string[] = DISPATCH_REPO_ALLOWLIST): string {
  const repoList = repoListOf(repos);
  return `#!/bin/sh
# Generated by FounderOS src/tools/claude-code-git-guard.ts — do not edit here.
PROTECTED_REPOS="${repoList}"
PROTECTED_BRANCHES="${PROTECTED_BRANCHES.join(" ")}"

${NORM_FN}

repo=""
for u in "$(git config --get "remote.$1.url" 2>/dev/null)" "$(git config --get "remote.$1.pushurl" 2>/dev/null)" "$1" "$2"; do
  [ -n "$u" ] || continue
  n=$(norm "$u")
  for p in $PROTECTED_REPOS; do
    [ "$n" = "$p" ] && repo="$p"
  done
done
[ -n "$repo" ] || exit 0

status=0
while read -r local_ref local_sha remote_ref remote_sha; do
  branch="\${remote_ref#refs/heads/}"
  for p in $PROTECTED_BRANCHES; do
    if [ "$branch" = "$p" ]; then
      echo "claude_code: refused push to $branch on $repo. Product repos change only through a reviewed PR: push a feature branch and open a DRAFT PR to beta (pr-brain gates it), or file the work with /task." >&2
      status=1
    fi
  done
done
exit $status
`;
}

/**
 * The `gh` wrapper. Refuses, on a protected repo:
 *   - pr merge, repo delete/archive/rename/edit, release create/delete
 *     (target = -R/--repo, else any argument naming the repo or its URL, else the
 *     cwd's origin)
 *   - api calls with a write method (explicit -X/--method, or -f/-F/--input, which
 *     make gh POST) on a repos/<owner>/<repo> path
 *   - any GraphQL mutation (it names nodes, not repos, so the repo can't be read)
 * Everything else execs the real gh unchanged.
 */
export function ghWrapper(realGh: string, repos: readonly string[] = DISPATCH_REPO_ALLOWLIST): string {
  return `#!/bin/sh
# Generated by FounderOS src/tools/claude-code-git-guard.ts — do not edit here.
REAL_GH=${shellQuote(realGh)}
PROTECTED_REPOS="${repoListOf(repos)}"

${NORM_FN}

protected() {
  n=$(norm "$1")
  for p in $PROTECTED_REPOS; do
    case "$n" in "$p"|"$p"/*) return 0 ;; esac
  done
  return 1
}

refuse() {
  echo "claude_code: refused \\\`gh $CMD\\\` on a product repo. Merges, repo changes and API writes there go through the founder: open a DRAFT PR to beta (pr-brain gates it) or file the work with /task." >&2
  exit 1
}

CMD="$*"
case "$1 $2" in
  "pr merge"|"repo delete"|"repo archive"|"repo rename"|"repo edit"|"release create"|"release delete")
    target=""; prev=""; hit=0
    for a in "$@"; do
      case "$prev" in -R|--repo) target="$a" ;; esac
      case "$a" in --repo=*) target="\${a#--repo=}" ;; esac
      protected "$a" && hit=1
      prev="$a"
    done
    if [ -n "$target" ]; then protected "$target" && refuse
    elif [ "$hit" = 1 ]; then refuse
    else protected "$(git config --get remote.origin.url 2>/dev/null)" && refuse
    fi
    ;;
esac

if [ "$1" = "api" ]; then
  method=""; body=0; graphql=0; mutation=0; hit=0; prev=""
  for a in "$@"; do
    case "$prev" in -X|--method) method="$a" ;; esac
    case "$a" in
      --method=*) method="\${a#--method=}" ;;
      -X?*) method="\${a#-X}" ;;
      -f|-F|--field|--raw-field|--input|--field=*|--raw-field=*|--input=*) body=1 ;;
      graphql) graphql=1 ;;
    esac
    lower=$(printf '%s' "$a" | tr 'A-Z' 'a-z')
    case "$lower" in *mutation*) mutation=1 ;; esac
    for p in $PROTECTED_REPOS; do
      case "$lower" in *repos/"$p"|*repos/"$p"/*|*repos/"$p"\\?*) hit=1 ;; esac
    done
    prev="$a"
  done
  m=$(printf '%s' "$method" | tr 'a-z' 'A-Z')
  [ -n "$m" ] || { [ "$body" = 1 ] && m=POST || m=GET; }
  [ "$graphql" = 1 ] && [ "$mutation" = 1 ] && refuse
  [ "$hit" = 1 ] && [ "$m" != GET ] && [ "$m" != HEAD ] && refuse
fi

exec "$REAL_GH" "$@"
`;
}

function shellQuote(v: string): string {
  return `'${v.replace(/'/g, `'\\''`)}'`;
}

/** The first `gh` on PATH that is not the wrapper itself, or null. */
export function findRealGh(path: string | undefined, guardBin: string): string | null {
  for (const dir of (path ?? "").split(delimiter)) {
    if (!dir || dir === guardBin) continue;
    const candidate = join(dir, "gh");
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

/** Where the hook is written: under the service user's home, never a shared /tmp. */
export function gitGuardDir(home: string = process.env["HOME"] ?? "/home/founderos"): string {
  return join(home, ".cache/founderos/claude-code-git-hooks");
}

/**
 * Writes `file` only when its content changed, through a temp file and a rename,
 * so a run that is executing the old copy never reads a half-written one (runs
 * overlap: each may take 15 minutes). Found by the security review of #747.
 */
function writeExecutableAtomically(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  writeFileSync(tmp, content, { mode: 0o755 });
  chmodSync(tmp, 0o755);
  renameSync(tmp, file);
}

/**
 * Writes the hook and, when a real gh exists on `path`, the gh wrapper (every
 * run, so a code change reaches the next run). Returns the dir.
 */
export function installGitGuard(dir: string = gitGuardDir(), path: string | undefined = process.env["PATH"]): string {
  mkdirSync(join(dir, "bin"), { recursive: true });
  writeExecutableAtomically(join(dir, "pre-push"), prePushHook());
  const realGh = findRealGh(path, join(dir, "bin"));
  if (realGh) writeExecutableAtomically(join(dir, "bin", "gh"), ghWrapper(realGh));
  return dir;
}

/**
 * GIT_CONFIG_COUNT/KEY_n/VALUE_n that point core.hooksPath at the guard, and a PATH
 * that finds the gh wrapper first. Appends after any GIT_CONFIG entries the base
 * environment already carries instead of replacing them.
 */
export function gitGuardEnv(hooksDir: string, base: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  const n = Number.parseInt(base["GIT_CONFIG_COUNT"] ?? "0", 10) || 0;
  return {
    GIT_CONFIG_COUNT: String(n + 1),
    [`GIT_CONFIG_KEY_${n}`]: "core.hooksPath",
    [`GIT_CONFIG_VALUE_${n}`]: hooksDir,
    // The gh wrapper shadows the real gh for everything the run starts.
    PATH: base["PATH"] ? `${join(hooksDir, "bin")}${delimiter}${base["PATH"]}` : join(hooksDir, "bin"),
  };
}

